        <h2 id="information-we-collect">1. Information We Collect</h2>
        <p>We collect information that you provide directly to us, and information generated as part of using
            the collection/recycling pickup service.</p>

        <h3>Account information</h3>
        <ul>
            <li>Name, email address, and phone number</li>
            <li>Password (stored in encrypted/hashed form — we never store or can view your plain-text password)</li>
            <li>Profile photo (optional, if you choose to upload one)</li>
            <li>Account role (e.g. customer or vendor/site incharge)</li>
        </ul>

        <h3>Pickup request &amp; collection information</h3>
        <ul>
            <li>Pickup address and location notes you enter</li>
            <li>Type and estimated weight/quantity of scrap material</li>
            <li>Preferred pickup date and any notes you add</li>
            <li>Photos related to the collection process (e.g. collection proof or challan images), where applicable to your account type</li>
            <li>Status history of your pickup/collection requests (e.g. pending, assigned, dispatched, completed)</li>
        </ul>

        <h3>Information collected automatically</h3>
        <ul>
            <li>Basic technical data needed to operate the app, such as login session tokens</li>
            <li>Standard server logs (e.g. IP address, request timestamps) generated when the app communicates with our servers</li>
        </ul>
        <p>We do <strong>not</strong> use analytics SDKs, advertising SDKs, or crash-reporting SDKs in the mobile
            app, and we do not access your precise device location.</p>

        <h2 id="permissions">2. Device Permissions We Request</h2>
        <table>
            <tr><th>Permission</th><th>Why we ask for it</th></tr>
            <tr>
                <td>Camera / Photo Library</td>
                <td>To let you attach or update a profile photo, or capture collection/challan proof images as part of fulfilling a pickup request. Photos are only accessed when you actively choose to take or select one.</td>
            </tr>
            <tr>
                <td>Internet access</td>
                <td>Required for the app to communicate with our servers (e.g. logging in, submitting pickup requests, syncing job status).</td>
            </tr>
        </table>
        <p>We do not request access to your contacts, precise location/GPS, microphone, or SMS.</p>

        <h2 id="how-we-use">3. How We Use Your Information</h2>
        <ul>
            <li>To create and manage your account and authenticate you</li>
            <li>To process, assign, and fulfill pickup and collection requests</li>
            <li>To communicate with you about the status of your requests</li>
            <li>To coordinate between customers, our vendors/site incharges, and administrators so that a
                pickup can be completed</li>
            <li>To maintain records of collections (e.g. proof-of-collection images, quantities collected) for
                operational and compliance purposes</li>
            <li>To detect, prevent, and address technical issues, fraud, or misuse of the Service</li>
        </ul>
        <p>We do not sell your personal information, and we do not use it for third-party advertising.</p>

        <h2 id="sharing">4. How We Share Information</h2>
        <p>We share information only as necessary to operate the Service:</p>
        <ul>
            <li><strong>With vendors / site incharges</strong> assigned to a pickup, so they can carry out the
                collection (e.g. your name, phone number, and pickup address)</li>
            <li><strong>With our administrators</strong>, who oversee and manage collection operations</li>
            <li><strong>With service providers</strong> who help us host and operate the app's infrastructure,
                under obligations to protect your data and use it only to provide services to us</li>
            <li><strong>When required by law</strong>, to comply with legal obligations, enforce our terms, or
                protect the rights, property, or safety of TrustMeRecycle, our users, or others</li>
        </ul>
        <p>We do not share your information with third parties for their own marketing purposes.</p>

        <h2 id="retention">5. Data Retention</h2>
        <p>We retain account and collection-record information for as long as your account is active or as
            needed to provide the Service, comply with our legal and accounting obligations, resolve disputes,
            and enforce our agreements. When you request deletion of your account (see below), we delete or
            anonymize your personal information, except where we are required to retain certain records
            (e.g. completed collection records) for legal or operational reasons.</p>

        <h2 id="security">6. Data Security</h2>
        <p>We use reasonable technical and organizational measures to protect your information, including
